"""Original 24x32 battle sprite built to the measured spec of a 16-bit console battle sprite:
24x32 cell, ~15 colours, dark partial outline, head+hair 12 rows, face 5, torso 10, legs 8-10, three-quarter stance facing left.
python -I tools/art/sprites/serin.py <out.png> [scale]"""
import sys
from PIL import Image, ImageDraw

PAL = {
 'j': (62, 28, 12),    # hair darkest (hair outline)
 'H': (122, 58, 22),   # hair dark
 'h': (200, 106, 40),  # hair mid
 'i': (240, 176, 80),  # hair highlight strands
 'S': (240, 208, 168), # skin light
 's': (200, 144, 104), # skin mid
 'x': (138, 88, 56),   # skin dark (skin outline)
 'E': (32, 24, 32),    # eye
 'A': (208, 212, 224), # plate light / steel
 'a': (136, 144, 168), # plate mid
 'd': (72, 80, 104),   # plate dark (armour outline)
 'B': (64, 96, 200),   # tabard
 'b': (40, 60, 144),   # tabard dark
 'R': (200, 56, 56),   # red
 'Y': (216, 176, 96),  # belt, buckle, boot trim
 'P': (106, 90, 140),  # trousers
 'p': (64, 52, 88),    # trousers dark
 'T': (122, 74, 40),   # boot
 't': (60, 36, 20),    # boot dark (boot outline, sole)
 'G': (20, 44, 40),    # ground shadow
}
ROWS = """
.......j..j.............
......jijhhj.j..........
.....jihjhhhjhj.........
....jiihhhhhhhhj........
....jihhihhhhhhhj.......
...jihhhhhhHhhhhhj......
...jhhihhhhHHhhhhhj.....
...jhhhhhhHHHhhhhhhj....
...jhhhjxSSxHHHhhhhhj...
....jhjjSSSSxHHhhhhhj...
....jxSEESSSxHHHhhhhj...
....xSSEESSsxHHHhhhj....
....xSSSSsxjHHHhhhj.....
.....xsssxjjjjjjj.......
....ddaAAdAsAdd.........
...dAAAAadBBBBdaad......
..dAAAaadBBRBBBdaaad....
..dAaaadxBRRRBBdAaad....
.xSSSxddBBBRBBbdaadd....
.xSSSxdbBBBBBbbdxSxd....
.xSSxAdbbYYYYYbdxSSx....
..xxAd.dbbbRbbbdxxx.....
...Ad..dPPPPPPPd........
..Ad...dPpPPPpPPd.......
.Ad...dPPPPdPPPPd.......
Ad...dPPPPd.dPPPPd......
d...dPpPPd...dPpPPd.....
...tYTTTt.....tYTTTt....
..tTTTTt.......tTTTTt...
.tTTTTTt.......tTTTTTt..
.tttttt.........ttttttt.
GGGGGGGGG.....GGGGGGGGG.
""".strip('\n').split('\n')
assert len(ROWS) == 32 and all(len(r) == 24 for r in ROWS), [len(r) for r in ROWS]
scale = int(sys.argv[2]) if len(sys.argv) > 2 else 8
im = Image.new('RGBA', (24, 32), (0, 0, 0, 0))
px = im.load()
for y, r in enumerate(ROWS):
    for x, c in enumerate(r):
        if c != '.': px[x, y] = PAL[c] + (255,)
im.save(sys.argv[1].replace('.png', '-1x.png'))
big = im.resize((24 * scale, 32 * scale), Image.NEAREST)
# show on a dark floor tile so it reads like the battle screen
bg = Image.new('RGB', big.size, (34, 60, 54))
d = ImageDraw.Draw(bg)
for yy in range(0, bg.size[1], scale):
    for xx in range(0, bg.size[0], scale):
        if ((xx // scale) + (yy // scale)) % 2: d.rectangle((xx, yy, xx + scale - 1, yy + scale - 1), fill=(28, 50, 46))
bg.paste(big, (0, 0), big)
bg.save(sys.argv[1])
print(sys.argv[1], len({c for r in ROWS for c in r if c != '.'}), 'colours')
